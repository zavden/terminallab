const {test,expect}=require('@playwright/test');
const {pathToFileURL}=require('node:url');
const path=require('node:path');
const command=async(page,text)=>{await page.locator('#command-input').fill(text);await page.locator('#command-input').press('Enter');};
for(const mode of ['mac','windows']) test(`${mode}: offline Python paths, editor, input and files`,async({page})=>{
  test.setTimeout(90000);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const external=[];page.on('request',r=>{if(/^https?:/.test(r.url()))external.push(r.url());});
  await page.goto(pathToFileURL(path.resolve('index.html')).href);
  await page.locator('#platform-'+mode).click();
  await command(page,mode==='mac'?'touch hello.py':'New-Item hello.py -ItemType File');
  await page.getByRole('button',{name:'View file hello.py',exact:true}).dblclick();
  await page.locator('#preview-content').fill('import sys, math\nname = input("Name: ")\nprint("Hello", name, math.sqrt(81), sys.argv[1:])\nwith open("result.txt", "w") as f:\n    f.write("Created in Python")\n');
  await page.locator('#python-input-open').click();
  await page.locator('#python-stdin').fill('Ada');
  await page.getByRole('button',{name:'Done',exact:true}).click();
  await command(page,'python hello.py example');
  await expect(page.locator('#python-stop')).toBeHidden({timeout:60000});
  await expect(page.locator('#terminal-output')).toContainText('Hello Ada 9.0');
  await page.locator('#close-file').click();
  await expect(page.getByRole('button',{name:'View file result.txt',exact:true})).toBeVisible();
  await command(page,'cd Documents');
  await command(page,mode==='mac'?'python3 /Users/user/hello.py absolute':'py C:\\Users\\user\\hello.py absolute');
  await expect(page.locator('#python-stop')).toBeHidden({timeout:60000});
  await expect(page.locator('#terminal-output')).toContainText("['absolute']");
  await expect(page.getByRole('button',{name:'View file result.txt',exact:true})).toBeVisible();
  await page.reload();
  await command(page,'cat result.txt');
  await expect(page.locator('#terminal-output')).toContainText('Created in Python');
  expect(external).toEqual([]);expect(errors).toEqual([]);
});

test('Python errors, cancellation, local imports, editor persistence and limits',async({page})=>{
  test.setTimeout(90000);
  await page.goto('/');
  await page.locator('#platform-mac').click();
  await command(page,'touch main.py');
  await page.getByRole('button',{name:'View file main.py',exact:true}).dblclick();
  const editor=page.locator('#preview-content');
  await command(page,'echo "answer = 42" > helper.py');
  await editor.fill('import helper\nprint(helper.answer)\nraise ValueError("Example error")');
  await page.locator('#run-python').click();
  await expect(page.locator('#python-stop')).toBeHidden({timeout:60000});
  await expect(page.locator('#terminal-output')).toContainText('42');
  await expect(page.locator('#terminal-output')).toContainText('ValueError: Example error');
  await editor.fill('while True:\n    pass');
  await page.locator('#run-python').click();
  await expect(page.locator('#terminal-output')).toContainText('Running Python', {timeout:60000});
  await page.locator('#python-stop').click();
  await expect(page.locator('#terminal-output')).toContainText('Python stopped');
  await editor.fill('print("After stop")');
  await page.locator('#minimize-file').click();
  await page.locator('#restore-file').click();
  await expect(editor).toHaveValue('print("After stop")');
  await page.locator('#run-python').click();
  await expect(page.locator('#python-stop')).toBeHidden({timeout:60000});
  await expect(page.locator('#terminal-output')).toContainText('After stop');
  await editor.fill('with open("huge.txt", "w") as f:\n    f.write("x" * 100001)');
  await page.locator('#run-python').click();
  await expect(page.locator('#python-stop')).toBeHidden({timeout:60000});
  await expect(page.locator('#terminal-output')).toContainText('exceed lab limits');
  await page.locator('#close-file').click();
  await expect(page.getByRole('button',{name:'View file huge.txt',exact:true})).toHaveCount(0);
  await page.reload();
  await page.getByRole('button',{name:'View file main.py',exact:true}).dblclick();
  await expect(editor).toHaveValue(/100001/);
});
